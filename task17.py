SECONDS_IN_MINUTE = 60
SECONDS_IN_HOUR = 60 * SECONDS_IN_MINUTE  # 3600 секунд в часе

# 1. Объявите константу SECONDS_IN_DAY
SECONDS_IN_DAY = 24 * SECONDS_IN_HOUR  # секунд в дне

# 2. Объявите переменную total_seconds_in_ten_days
total_seconds_in_ten_days = 10 * SECONDS_IN_DAY

# 3. Распечатайте значение переменной total_seconds_in_ten_days
print(total_seconds_in_ten_days)